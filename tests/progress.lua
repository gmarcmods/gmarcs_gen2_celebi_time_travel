local Progress=assert(loadfile('mods/gen2/celebi_mod/lib/Progress.lua'))()
local bucket={}
local storage={get=function(_,k,default)return bucket[k]or default end,set=function(_,k,v)bucket[k]=v end}
local p=Progress.new(storage)
assert(p:phase()=='none')
assert(not p:deliver(function()return false end));assert(p:phase()=='none','full bag consumed delivery')
assert(p:deliver(function()return true end));assert(p:phase()=='delivered')
assert(not p:deliver(function()error('duplicate item grant')end))
assert(not p:handOver(1,'2026-10-17',function()return false end))
assert(p:handOver(1,'2026-10-17',function()return true end))
p=Progress.new(storage) -- reload must retain the inspection day
assert(p:phase()=='inspecting')
assert(not p:ready(1,'2026-10-17'))
assert(p:ready(2,'2026-10-17'),'native weekday change should finish inspection')
assert(p:ready(1,'2026-10-24'),'a full week must not restart the inspection')
assert(p:leaveWorkshop(2,'2026-10-18'));assert(p:phase()=='street')
assert(not p:returnBall(function()return false end));assert(p:phase()=='street')
assert(p:returnBall(function()return true end));assert(p:phase()=='restless')
assert(not p:placeBall(function()return false end));assert(p:phase()=='restless')
assert(p:placeBall(function()return true end));assert(p:phase()=='encounter')
p=Progress.new(storage);assert(p:phase()=='encounter','failed/interrupted catch must remain retryable')
assert(p:caught());assert(p:phase()=='caught')
assert(not p:placeBall(function()error('consumed a second ball')end))
assert(not p:caught(),'duplicate catch changed progress')
print('CELEBI PROGRESS PASS: item transactions, next-day inspection, reload and encounter retry')
